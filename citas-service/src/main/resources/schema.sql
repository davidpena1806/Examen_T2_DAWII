CREATE TABLE IF NOT EXISTS cita (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(20)  NOT NULL UNIQUE,
    paciente_id         BIGINT       NOT NULL,   -- referencia logica, sin FK (otro servicio)
    especialidad        VARCHAR(80)  NOT NULL,
    fecha_hora          TIMESTAMP    NOT NULL,
    profesional_codigo  VARCHAR(40)  NOT NULL,
    motivo              VARCHAR(200) NOT NULL,
    estado              VARCHAR(15)  NOT NULL,
    fecha_creacion      TIMESTAMP    NOT NULL,
    fecha_actualizacion TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cita_paciente ON cita (paciente_id);
CREATE INDEX IF NOT EXISTS idx_cita_agenda ON cita (profesional_codigo, fecha_hora);
